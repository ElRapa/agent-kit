#!/usr/bin/env python3
"""Build every theme file from design/tokens.json (stdlib only).

    python3 design/build.py                       # kiln -> design/dist/kiln/
    python3 design/build.py variants/nowu.json    # tokens.json + a variant -> design/dist/nowu/
    python3 design/build.py --check               # exit 1 when a committed dist file is stale

A variant is a partial tokens file: only the keys that differ (e.g. another accent). Keys are
merged deeply, so `{"semantic": {"accent": "cyan"}}` changes the accent and nothing else.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ANSI = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
HERDR = {  # herdr's theme.custom tokens -> our colour names
    "accent": "@accent", "panel_bg": "bg", "sidebar_bg": "surface", "active_row_bg": "raised",
    "selection_bg": "selection", "surface0": "surface", "surface1": "raised", "surface_dim": "bg",
    "overlay0": "faint", "overlay1": "muted", "text": "ink", "subtext0": "muted", "mauve": "violet",
    "green": "green", "yellow": "amber", "red": "red", "blue": "blue", "teal": "cyan", "peach": "pink",
}


def merge(base: dict, extra: dict) -> dict:
    out = dict(base)
    for k, v in extra.items():
        out[k] = merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def mix(a: str, b: str, t: float) -> str:
    pa = [int(a[i : i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i : i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(pa, pb, strict=True))


def resolve(t: dict, mode: str) -> dict[str, str]:
    """Every colour name of one mode, plus the semantic roles (accent, ok, …) as hex."""
    c = dict(t["modes"][mode])
    for role, name in t["semantic"].items():
        c[role] = c[name]
    return c


def ansi16(t: dict, mode: str) -> list[str]:
    c = resolve(t, mode)
    m = t["ansi"] | (t.get("ansi_light", {}) if mode == "light" else {})
    base = [c[m[n]] for n in ANSI]
    toward = c["ink"] if mode == "dark" else c["bg"]
    bright = [mix(x, toward, 0.28) for x in base]
    bright[0] = c[m["bright_black"]]
    bright[7] = c[m["bright_white"]]
    return base + bright


def css(t: dict) -> str:
    def block(mode: str) -> str:
        c = resolve(t, mode)
        lines = [f"  --{k}: {v};" for k, v in c.items()]
        g = ", ".join(c[n] for n in t["glow"])
        lines.append(f"  --glow: linear-gradient(120deg, {g});")
        return "\n".join(lines)

    fixed = [f"  --mono: {t['font']['mono']};", f"  --sans: {t['font']['sans']};"]
    fixed += [f"  --r-{k}: {v}px;" for k, v in t["radius"].items()]
    fixed += [f"  --s-{k}: {v}px;" for k, v in t["space"].items()]
    return (
        f"/* {t['name']} tokens, generated by agent-kit/design/build.py. Do not edit; edit tokens.json. */\n"
        f":root {{\n  color-scheme: dark light;\n" + "\n".join(fixed) + "\n" + block("dark") + "\n}\n"
        f"@media (prefers-color-scheme: light) {{\n  :root:not([data-theme=\"dark\"]) {{\n"
        + block("light").replace("\n", "\n  ") + "\n  }\n}\n"
        f":root[data-theme=\"light\"] {{\n" + block("light") + "\n}\n"
        f":root[data-theme=\"dark\"] {{\n" + block("dark") + "\n}\n"
    )


def ghostty(t: dict, mode: str) -> str:
    c = resolve(t, mode)
    lines = [f"# {t['name']} ({mode}), generated by agent-kit/design/build.py"]
    lines += [f"palette = {i}={x}" for i, x in enumerate(ansi16(t, mode))]
    lines += [
        f"background = {c['bg']}", f"foreground = {c['ink']}", f"cursor-color = {c['cursor']}",
        f"cursor-text = {c['bg']}", f"selection-background = {c['selection']}", f"selection-foreground = {c['ink']}",
    ]
    return "\n".join(lines) + "\n"


def herdr(t: dict) -> str:
    out = [
        f"# {t['name']} for herdr (agent-kit/design/build.py): paste below your [theme] table.",
        "# [theme.custom] always applies; [theme.custom.light] only with theme.auto_switch = true.",
    ]
    for mode, table in (("dark", "theme.custom"), ("light", "theme.custom.light")):
        c = resolve(t, mode)
        out.append(f"\n[{table}]")
        for key, name in HERDR.items():
            out.append(f'{key} = "{c[name.lstrip("@")]}"')
    return "\n".join(out) + "\n"


def starship(t: dict) -> str:
    c = resolve(t, "dark")
    pal = "\n".join(f'{k} = "{v}"' for k, v in c.items())
    g = t["glyphs"]
    return f"""# {t['name']} for starship, generated by agent-kit/design/build.py. Copy to ~/.config/starship.toml
# or keep your own and only take [palettes.{t['name']}] and `palette`.
palette = "{t['name']}"
add_newline = true
format = "$directory$git_branch$git_status$python$nodejs$env_var$cmd_duration$line_break$character"

[directory]
style = "bold ink"
truncation_length = 3
truncation_symbol = "…/"

[git_branch]
format = "[{g['sep']} $branch]($style) "
style = "muted"

[git_status]
format = "[$all_status$ahead_behind]($style) "
style = "amber"

[python]
format = "[{g['sep']} py $version]($style) "
style = "faint"

[nodejs]
format = "[{g['sep']} node $version]($style) "
style = "faint"

# agent-stack profile, e.g. "● work-eco" (AP_PROFILE comes from `ap use`).
[env_var.AP_PROFILE]
format = "[{g['dot']} $env_value]($style) "
style = "bold violet"

[cmd_duration]
format = "[{g['sep']} $duration]($style) "
style = "faint"

[character]
success_symbol = "[{g['prompt']}](bold violet)"
error_symbol = "[{g['prompt']}](bold red)"

[palettes.{t['name']}]
{pal}
"""


def gemini(t: dict) -> str:
    c = resolve(t, "dark")
    theme = {
        "name": t["name"], "type": "custom",
        "background": {"primary": c["bg"], "diff": {"added": mix(c["green"], c["bg"], 0.78),
                                                   "removed": mix(c["red"], c["bg"], 0.78)}},
        "text": {"primary": c["ink"], "secondary": c["muted"], "link": c["link"], "accent": c["accent"],
                 "response": c["ink"]},
        "border": {"default": c["line"]},
        "status": {"success": c["ok"], "warning": c["warn"], "error": c["err"]},
        "ui": {"comment": c["faint"], "symbol": c["soft"], "active": c["accent"], "focus": c["cyan"],
               "gradient": [c[n] for n in t["glow"]]},
    }
    return json.dumps(theme, indent=2) + "\n"


def lua(t: dict) -> str:
    def rgb(h: str) -> str:
        r, g, b = (int(h[i : i + 2], 16) / 255 for i in (1, 3, 5))
        return f"{{ red = {r:.3f}, green = {g:.3f}, blue = {b:.3f} }}"

    parts = [f"-- {t['name']} colours for Hammerspoon, generated by agent-kit/design/build.py.", "return {"]
    parts.append(f'  name = "{t["name"]}",')
    parts.append(f'  font = {{ mono = "{t["font"]["mono_name"]}" }},')
    for mode in ("dark", "light"):
        c = resolve(t, mode)
        parts.append(f"  {mode} = {{")
        parts += [f"    {k} = {rgb(v)}," for k, v in c.items()]
        parts.append("  },")
    parts.append(f"  glow = {{ {', '.join(repr(n).replace(chr(39), chr(34)) for n in t['glow'])} }},")
    parts.append("}")
    return "\n".join(parts) + "\n"


def flat(t: dict) -> str:
    out = {k: v for k, v in t.items() if k not in ("modes",)}
    out["colors"] = {m: resolve(t, m) for m in t["modes"]}
    out["ansi16"] = {m: ansi16(t, m) for m in t["modes"]}
    return json.dumps(out, indent=2, ensure_ascii=False) + "\n"


def files(t: dict) -> dict[str, str]:
    preview = (HERE / "preview.html").read_text()
    style = css(t) + (HERE / "components.css").read_text()
    return {
        "tokens.css": css(t),
        "components.css": (HERE / "components.css").read_text(),
        f"ghostty/{t['name']}": ghostty(t, "dark"),
        f"ghostty/{t['name']}-light": ghostty(t, "light"),
        "herdr.toml": herdr(t),
        "starship.toml": starship(t),
        "gemini.json": gemini(t),
        f"{t['name']}.lua": lua(t),
        f"{t['name']}.json": flat(t),
        "preview.html": preview.replace("/*STYLE*/", style).replace("{{name}}", t["name"]),
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    variants = [a for a in argv if not a.startswith("-")]
    tokens = json.loads((HERE / "tokens.json").read_text())
    stale = []
    builds = [tokens] + [merge(tokens, json.loads((HERE / v).read_text())) for v in variants]
    if check and not variants:
        builds += [merge(tokens, json.loads(p.read_text())) for p in sorted((HERE / "variants").glob("*.json"))]
    for t in builds:
        out = HERE / "dist" / t["name"]
        for rel, text in files(t).items():
            p = out / rel
            if check:
                if not p.exists() or p.read_text() != text:
                    stale.append(str(p.relative_to(HERE)))
                continue
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
        if not check:
            print(f"built {t['name']} -> {out.relative_to(HERE.parent)}")
    if stale:
        print("stale, run python3 design/build.py (and each variant):\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
